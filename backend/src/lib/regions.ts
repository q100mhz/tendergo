// The first two digits of an INN are the tax-office region; matches the subject code for nearly all customers.
export function regionFromInn(inn: string | null | undefined): string | null {
  if (!inn || !/^\d{10}(\d{2})?$/.test(inn)) return null;
  const code = inn.slice(0, 2);
  return code in REGIONS ? code : null;
}

