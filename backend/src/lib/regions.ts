const tokenize = (s: string) =>
  s
    .toLowerCase()
    .replace(/ё/g, "е")
    .split(/[^а-яa-z0-9-]+/)
    .filter(Boolean);

/** Finds the region mentioned earliest in the text, so "Респ Татарстан, г Казань, ул Московская" gives Татарстан. */
export function regionFromText(text: string | null | undefined): string | null {
  if (!text) return null;
  const tokens = tokenize(text);
  let best: { code: string; at: number } | null = null;
  for (const [code, keys] of Object.entries(REGION_KEYS)) {
    for (const key of keys) {
      const words = key.split(" ");
      for (let i = 0; i < tokens.length && (!best || i < best.at); i++) {
        if (words.every((w, j) => tokens[i + j] === w)) {
          best = { code, at: i };
          break;
        }
      }
    }
  }
  return best?.code ?? null;
}

